"""Native renderers: report document -> Markdown / standalone HTML.

The HTML renderer produces a self-contained, print-ready document with
consulting-grade typography: branded cover, table of contents, numbered
sections, styled tables and footer page numbers (via CSS paged media).
"""
from __future__ import annotations

import html as _html
from datetime import datetime
from typing import Any


def render_markdown(doc: dict[str, Any]) -> str:
    lines: list[str] = [
        f"# {doc['title']} — {doc['subtitle']}",
        "",
        f"*Generated by {doc['brand']} on {_date(doc)}*",
        "",
        "## Table of Contents",
    ]
    for i, sec in enumerate(doc["sections"], start=1):
        lines.append(f"{i}. {sec['heading']}")
    lines.append("")

    for i, sec in enumerate(doc["sections"], start=1):
        lines += [f"## {i}. {sec['heading']}", ""]
        for block in sec["blocks"]:
            lines += _md_block(block)
        lines.append("")
    return "\n".join(lines)


def _md_block(block: dict[str, Any]) -> list[str]:
    kind = block.get("type")
    if kind == "p":
        return [block.get("text", ""), ""]
    if kind == "callout":
        return [f"> {block.get('text', '')}", ""]
    if kind == "kv":
        out = ["| | |", "| --- | --- |"]
        out += [f"| **{k}** | {v} |" for k, v in block.get("items", [])]
        out.append("")
        return out
    if kind == "list":
        marker = "1." if block.get("ordered") else "-"
        return [f"{marker} {item}" for item in block.get("items", [])] + [""]
    if kind == "table":
        cols = block.get("columns", [])
        out = ["| " + " | ".join(cols) + " |", "| " + " | ".join(["---"] * len(cols)) + " |"]
        out += ["| " + " | ".join(str(c) for c in row) + " |" for row in block.get("rows", [])]
        out.append("")
        return out
    return []


