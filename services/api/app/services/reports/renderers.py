def render_html(doc: dict[str, Any]) -> str:
    esc = _html.escape
    parts: list[str] = [
        "<!doctype html><html><head><meta charset='utf-8'/>",
        f"<title>{esc(doc['title'])} — {esc(doc['subtitle'])}</title>",
        f"<style>{_CSS}</style></head><body><div class='page'>",
        "<div class='cover'>",
        f"<div class='brand'>{esc(doc['brand'])}</div>",
        f"<h1>{esc(doc['title'])}</h1>",
        f"<p class='subtitle'>{esc(doc['subtitle'])}</p>",
        f"<div class='meta'>Generated {esc(_date(doc))} · Confidential — internal use</div>",
        "</div>",
        "<div class='toc'><h2>Table of Contents</h2><ol>",
    ]
    for i, sec in enumerate(doc["sections"], start=1):
        parts.append(f"<li><a href='#sec-{i}'>{esc(sec['heading'])}</a></li>")
    parts.append("</ol></div>")

    for i, sec in enumerate(doc["sections"], start=1):
        parts.append(f"<section id='sec-{i}'><h2 class='sec'><span class='num'>{i:02d}</span>{esc(sec['heading'])}</h2>")
        for block in sec["blocks"]:
            parts.append(_html_block(block))
        parts.append("</section>")

    parts.append(
        f"<footer><span>{esc(doc['brand'])} · {esc(doc['title'])}</span>"
        f"<span>{esc(doc['subtitle'])}</span></footer>"
    )
    parts.append("</div></body></html>")
    return "".join(parts)


def _html_block(block: dict[str, Any]) -> str:
    esc = _html.escape
    kind = block.get("type")
    if kind == "p":
        return f"<p>{esc(block.get('text', ''))}</p>"
    if kind == "callout":
        return f"<div class='callout'>{esc(block.get('text', ''))}</div>"
    if kind == "kv":
        rows = "".join(
            f"<tr><td>{esc(str(k))}</td><td>{esc(str(v))}</td></tr>"
            for k, v in block.get("items", [])
        )
        return f"<table class='kv'>{rows}</table>"
    if kind == "list":
        tag = "ol" if block.get("ordered") else "ul"
        items = "".join(f"<li>{esc(str(i))}</li>" for i in block.get("items", []))
        return f"<{tag}>{items}</{tag}>"
    if kind == "table":
        head = "".join(f"<th>{esc(str(c))}</th>" for c in block.get("columns", []))
        body = "".join(
            "<tr>" + "".join(f"<td>{esc(str(c))}</td>" for c in row) + "</tr>"
            for row in block.get("rows", [])
        )
        return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"
    return ""


def _date(doc: dict[str, Any]) -> str:
    raw = doc.get("generated_at", "")
    try:
        return datetime.fromisoformat(raw).strftime("%B %d, %Y")
    except ValueError:
        return raw
